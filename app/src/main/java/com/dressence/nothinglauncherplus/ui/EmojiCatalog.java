package com.dressence.nothinglauncherplus.ui;

import android.content.Context;
import android.graphics.Paint;

import com.dressence.nothinglauncherplus.anim.DotEffect;
import com.dressence.nothinglauncherplus.anim.Motion;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Every emoji with its picker group, motion and dot-matrix effect, from {@code assets/emoji_motions.tsv}
 * (generated by {@code tools/gen_emoji_motions.py}). Only emojis the system font can draw are
 * listed.
 */
final class EmojiCatalog {

    static final String[] GROUP_TITLES = {"Smileys", "People", "Animals & nature",
            "Food & drink", "Travel & places", "Activities", "Objects", "Symbols", "Flags"};
    static final String[] GROUP_ICONS = {"😀", "👋", "🐻",
            "🍔", "✈️", "⚽", "💡", "❤️",
            "🏁"};

    static final class Entry {
        final String emoji;
        final int group;
        final Motion motion;
        final DotEffect effect;
        final String name;

        Entry(String emoji, int group, Motion motion, DotEffect effect, String name) {
            this.emoji = emoji;
            this.group = group;
            this.motion = motion;
            this.effect = effect;
            this.name = name;
        }
    }

    private static EmojiCatalog instance;

    final List<Entry> entries;
    private final Map<String, Entry> byKey;

    static synchronized EmojiCatalog get(Context context) {
        if (instance == null) {
            instance = load(context.getApplicationContext());
        }
        return instance;
    }

    private EmojiCatalog(List<Entry> entries) {
        this.entries = Collections.unmodifiableList(entries);
        byKey = new HashMap<>();
        for (Entry entry : entries) {
            byKey.put(key(entry.emoji), entry);
        }
    }

    private static EmojiCatalog load(Context context) {
        List<Entry> entries = new ArrayList<>();
        Paint paint = new Paint();
        try (BufferedReader in = new BufferedReader(new InputStreamReader(
                context.getAssets().open("emoji_motions.tsv"), StandardCharsets.UTF_8))) {
            for (String line; (line = in.readLine()) != null; ) {
                if (line.isEmpty() || line.startsWith("#")) {
                    continue;
                }
                String[] f = line.split("\t", 5);
                if (f.length == 5 && paint.hasGlyph(f[0])) {
                    entries.add(new Entry(f[0], Integer.parseInt(f[1]), Motion.parse(f[2]),
                            DotEffect.parse(f[3]), f[4]));
                }
            }
        } catch (IOException | NumberFormatException e) {
            // A broken asset only costs the picker; typed emojis still get a motion.
        }
        return new EmojiCatalog(entries);
    }

    Entry find(String emoji) {
        return emoji == null ? null : byKey.get(key(emoji));
    }

    /** The motion that suits {@code text}: its emoji's own, or a gentle pulse for anything else. */
    Motion motionFor(String text) {
        Entry entry = find(text);
        return entry != null ? entry.motion : Motion.PULSE;
    }

    /** The effect that suits {@code text}: its emoji's own, or a sparkle for anything else. */
    DotEffect effectFor(String text) {
        Entry entry = find(text);
        return entry != null ? entry.effect : DotEffect.SPARKLE;
    }

    /** Ignores variation selectors and skin tones, so every variant finds its base emoji. */
    private static String key(String emoji) {
        StringBuilder sb = new StringBuilder(emoji.length());
        emoji.codePoints()
                .filter(cp -> cp != 0xFE0F && (cp < 0x1F3FB || cp > 0x1F3FF))
                .forEach(sb::appendCodePoint);
        return sb.toString();
    }
}
